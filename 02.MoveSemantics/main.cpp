using namespace std;

/*
==========================================================================================================================================
                                                         Семантика перенесення
==========================================================================================================================================

                                                         Семантика перенесення
  Семантика перенесення (move semantics) — це концепція та набір засобів, які дозволяють ефективно переміщувати внутрішні ресурси
  з одного об'єкта в інший, повністю уникаючи дорогого глибокого копіювання.

  Семантика перенесення працює у мові завдяки взаємодії трьох основних інструментів:
  1. rvalue-посилання (T&&) — спеціальний тип посилань, який дозволяє компілятору ідентифікувати тимчасові об'єкти.
  2. Конструктор перенесення та оператор присвоювання перенесенням — спеціальні методи всередині класу, які описують, як саме потрібно
  забрати ресурси в іншого об'єкта та занулити його.
  3. Функція std::move() — інструмент, який дає сигнал компілятору: що іменований об'єкт (lvalue), більше не потрібен — він по суті
  тимчасовий, можна забрати його ресурси.

                                                          rvalue-посилання (&&)
  В С++ існують такі поняття як lvalue і rvalue:
  - lvalue (від left value — те, що може стояти ліворуч від =; іноді розшифровують як locator value) — це вираз, який посилається
  на конкретну комірку пам'яті. У такого об'єкта є ім'я, і ви можете взяти його адресу за допомогою оператора &. Вони зазвичай
  «живуть» довго (до кінця області видимості).
  - rvalue (від right value — значення, яке може стояти лише праворуч від =) — це тимчасове значення, яке зазвичай не має імені
  та власної постійної адреси в пам'яті (це тимчасові проміжні результати обчислень або літерали). Вони «вмирають» одразу після
  виконання рядка коду.
  Говорячи простою мовою, lvalue та rvalue визначають, чи є в об'єкта постійна адреса в пам'яті та як довго він живе.
  У виразі int x = 10: x - lvalue, а 10 - rvalue.

  rvalue-посилання (rvalue reference, &&) — це тип посилання в C++, що може зв'язуватися виключно з тимчасовими об'єктами (rvalue).

  Коли ми використовуємо rvalue-посилання, ми даємо сигнал компілятору, що: об'єкт тимчасовий, він все одно одразу буде знищений,
  тому ми можемо без шкоди забрати його ресурси.

                                          Конструктор перенесення та Оператор присвоєння перенесенням
  Конструктор перенесення (move constructor) — це спеціальний конструктор, який забирає (переміщує) ресурси з одного об'єкта 
  (зазвичай тимчасового, rvalue) у новий об'єкт, що створюється, замість того, щоб копіювати їх. 

  Алгоритм конструктора перенесення:
   1. Забрати покажчик other у списку ініціалізації: name(other.name) - жодного new і копіювання даних;
   2. Скопіювати прості поля (теж у списку ініціалізації);
   3. Обнулити other: other.name = nullptr; - інакше деструктор other звільнить пам'ять, яка тепер належить нам.
   Перевірка самоприсвоєння і звільнення старої пам'яті НЕ потрібні: об'єкт новий, старої пам'яті в нього ще немає.

  Оператор присвоювання перенесенням (move assignment operator) — це спеціальний перевантажений оператор класу, який заміщує вміст
  вже існуючого об'єкта ресурсами іншого (зазвичай тимчасового, rvalue) об'єкта, замість того, щоб копіювати їх.

  Алгоритм оператора присвоєння перенесенням:
   1. Обов'язково: if(this == &other) { return *this; } - захист від самоприсвоєння  a = std::move(a);
   2. Звільнити стару пам'ять;
   3. Забрати покажчик other: name = other.name; - жодного new і копіювання даних;
   4. Скопіювати прості поля;
   5. Обнулити other: other.name = nullptr; - інакше два об'єкти володітимуть однією пам'яттю → подвійний delete[];
   6. Повернути: return *this; - сам об'єкт, для того щоб працював ланцюжок викликів.

  Конструктор перенесення та оператор присвоєння перенесенням служать для оптимізації продуктивності. Вони завжди приймають параметром
  rvalue-посилання на об'єкт того ж класу (Ім'яКласу&& other).
                                                                    
                                                            Функція std::move()
  std::move() — це стандартна функція з бібліотеки <utility>, яка використовується для примусового перетворення lvalue
  (звичайного іменованого об'єкта) на rvalue-посилання. Вона не переміщує жодних даних сама по собі. Вона є лише сигналом для
  компілятора: «цей об'єкт тимчасовий, з цього моменту можна забрати в нього ресурси».

                                                               ПРАВИЛО ПЯ'ТИ
  Правило п'яти: деструктор, конструктор копіювання, operator= копіюванням, конструктор перенесення, operator= перенесенням.
  Перші три обов'язкові для класу з ресурсом (правило трьох), два останні — оптимізація швидкості.
*/

class Student
{
private:
    char* name;
    int age;

    // Після перенесення name == nullptr, а cout << nullptr для char* — аварійне завершення.
    // Тому для виведення використовуємо цей метод
    const char* nameOrEmpty() const
    {
        if (name == nullptr)
        {
            return "";
        }
        return name;
    }

public:
    Student(const char* name, int age) : name(nullptr), age(age)
    {
        setName(name);
        cout << "  [+] Конструктор: " << this->name << endl;
    }

    Student(const Student& other) : name(nullptr), age(other.age)
    {
        setName(other.name);
        cout << "  [=] Копіювання: " << name << endl;
    }

    // ===== КОНСТРУКТОР ПЕРЕНЕСЕННЯ: забираємо покажчик, other залишаємо порожнім =====
    Student(Student&& other) : name(other.name), age(other.age)
    {
        other.name = nullptr;       // інакше деструктор other звільнить пам'ять, яка тепер належить нам
        other.age = 0;
        cout << "  [>] Перенесення: " << name << endl;
    }

    Student& operator=(const Student& other)
    {
        cout << "  [op=] Присвоєння копіюванням: " << other.name << endl;
        if (this == &other)
        {
            return *this;
        }
        setName(other.name);
        age = other.age;
        return *this;
    }

    // ===== ПРИСВОЄННЯ ПЕРЕНЕСЕННЯМ =====
    Student& operator=(Student&& other)
    {
        cout << "  [op>] Присвоєння перенесенням: " << other.nameOrEmpty() << endl;
        if (this == &other)
        {
            return *this;
        }
        delete[] name;              // звільняємо СВОЮ стару пам'ять
        name = other.name;          // забираємо чужу
        age = other.age;
        other.name = nullptr;       // other більше нею не володіє
        other.age = 0;
        return *this;
    }

    ~Student()
    {
        cout << "  [-] Деструктор: " << nameOrEmpty() << endl;
        delete[] name;              // delete[] nullptr — безпечно, нічого не відбувається
    }

    void setName(const char* name)
    {
        delete[] this->name;
        size_t length = strlen(name) + 1;
        this->name = new char[length];
        strcpy_s(this->name, length, name);
    }

    void print() const
    {
        cout << "  " << nameOrEmpty() << ", вік: " << age << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "1. Копіювання з lvalue" << endl;
    Student a("Олена", 20);
    Student b = a;                  // a — lvalue, житиме далі → копіювання
    a.print();
    b.print();                      // у b власна копія рядка

    cout << "2. Перенесення з std::move" << endl;
    Student c = std::move(a);       // a більше не потрібен → перенесення
    c.print();                      // c забрав рядок у a: пам'ять не виділялася і не копіювалася
    a.print();                      // a порожній

    cout << "3. Присвоєння тимчасового об'єкта" << endl;
    b = Student("Тарас", 25);       // тимчасовий об'єкт — rvalue → присвоєння перенесенням
    b.print();                      // [-] Деструктор: без імені — знищився вже «спустошений» тимчасовий об'єкт

    cout << "4. Порожньому об'єкту можна присвоїти нове значення" << endl;
    a = Student("Марія", 19);
    a.print();

    cout << "Кінець main" << endl;
    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - Ознака перенесення — у виводі [>] замість [=]: пам'ять не виділялася і не копіювалася.
  - Найголовніше в перенесенні — обнулити покажчик в other. Забули → два об'єкти володіють однією пам'яттю → подвійний delete[].
  - Після перенесення об'єкт порожній, тому деструктор і всі методи, які читають name, мають бути готові до nullptr.
  - Компілятор часто пропускає і копіювання, і перенесення (copy elision, RVO):
        Student s = Student("Ян", 18);      // лише [+], ні [=], ні [>]
        Student s = makeStudent();           // об'єкт створюється одразу «на місці»
    Це законна оптимізація (з C++17 для тимчасових об'єктів — обов'язкова). Тому якщо у виводі «зник» виклик конструктора
    копіювання чи перенесення — це не помилка. Для демонстрації використовуйте std::move і присвоєння тимчасового об'єкта.
  - Не пишіть return std::move(local); — це заважає компілятору застосувати оптимізацію, яка краща за перенесення.
  - Після std::move(a) не читайте a, доки не присвоїте йому нове значення.
  - Якщо в класі написано власний деструктор, конструктор копіювання або operator=, компілятор НЕ генерує перенесення сам.
    Тоді для rvalue використовується копіювання: програма працює правильно, але повільніше.
  - Для класів без динамічної пам'яті (Fraction) перенесення нічого не дає: переносити нема чого, стандартні методи достатні.
  - Бонус: у реальному коді конструктор перенесення позначають noexcept — пояснимо в темі винятків.

  ==========================================================================================================================================

  ПРАКТИКА

  1. Клас Message (повідомлення в месенджері) — правило п'яти:
     - поле (private): char* text;
     - конструктор Message(const char* text);
     - деструктор (має бути готовий до text == nullptr);
     - конструктор копіювання і operator= копіюванням — у кожному виведіть повідомлення [=];
     - конструктор перенесення і operator= перенесенням — забрати покажчик text, в other: text = nullptr;
       у кожному виведіть повідомлення [>];
     - метод print() const — виводить текст повідомлення, а для text == nullptr — «(порожньо)».
     Функція поза класом: void swapMessages(Message& a, Message& b) — міняє два повідомлення місцями через std::move:
         Message temp = std::move(a);
         a = std::move(b);
         b = std::move(temp);
     У main:
       а) створіть два повідомлення, поміняйте їх місцями через swapMessages і виведіть обидва;
          у виводі мають бути лише [>] і жодного [=] — тексти не копіювалися;
       б) присвойте першому повідомленню нове значення: first = Message("Нове повідомлення"); — яке повідомлення
          ([=] чи [>]) з'явилося у виводі і чому?
*/
